def sanitize_tool_output(obj: Any) -> Any:
    """Recursively strip potential instruction-override sequences from data values."""
    if isinstance(obj, str):
        cleaned = re.sub(r"(ignore\s+all\s+instructions|system\s+prompt|<script)", "[filtered]", obj, flags=re.IGNORECASE)
        return cleaned
    elif isinstance(obj, dict):
        return {k: sanitize_tool_output(v) for k, v in obj.items()}
    elif isinstance(obj, list):
        return [sanitize_tool_output(v) for v in obj]
    return obj


class PlannerAssistant:
    """
    Unified Planner Assistant providing interchangeable LLM and Offline backends.
    Defaults to offline deterministic backend when ANTHROPIC_API_KEY is not configured.
    """

    def __init__(
        self,
        outputs_dir: Optional[Union[str, Path]] = None,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
    ):
        self.outputs_dir = outputs_dir
        self.offline_assistant = OfflinePlannerAssistant(outputs_dir=outputs_dir)
        self.tools = self.offline_assistant.tools
        self.api_key = api_key or os.getenv("ANTHROPIC_API_KEY")
        self.model = model or os.getenv("ASSISTANT_MODEL", ASSISTANT_MODEL)

    def is_llm_available(self) -> bool:
        """Check whether LLM backend is configured and ready."""
        return bool(HAS_ANTHROPIC and self.api_key and self.api_key.strip())

    def execute_tool(self, tool_name: str, tool_input: Dict[str, Any]) -> Dict[str, Any]:
        """Execute a tool by name with arguments."""
        if tool_name == "get_district":
            return self.tools.get_district(**tool_input)
        elif tool_name == "rank_districts":
            return self.tools.rank_districts(**tool_input)
        elif tool_name == "explain_rank":
            return self.tools.explain_rank(**tool_input)
        elif tool_name == "get_corridor_gaps":
            return self.tools.get_corridor_gaps()
        elif tool_name == "get_recommended_sites":
            return self.tools.get_recommended_sites(**tool_input)
        elif tool_name == "get_uncertainty":
            return self.tools.get_uncertainty(**tool_input)
        elif tool_name == "run_whatif":
            return self.tools.run_whatif(**tool_input)
        elif tool_name == "get_data_quality":
            return self.tools.get_data_quality(**tool_input)
        elif tool_name == "list_limitations":
            return self.tools.list_limitations()
        else:
            return {"status": "error", "message": f"Unknown tool: {tool_name}"}

    def answer(self, question: str, district_context: Optional[str] = None) -> Dict[str, Any]:
        """
        Answer a planner question using the LLM backend if available, or offline backend.
        """
        if not self.is_llm_available():
            res = self.offline_assistant.answer(question, district_context=district_context)
            res["fallback_from_llm"] = False
            return res

        try:
            client = anthropic.Anthropic(api_key=self.api_key)
            user_content = question
            if district_context:
                user_content += f"\n(Context: User is viewing district '{district_context}')"

            messages = [{"role": "user", "content": user_content}]
            evidence_collected: List[Dict[str, Any]] = []
            warnings_collected: List[str] = []

            # Tool-use loop
            for _ in range(5):  # Max 5 turns
                response = client.messages.create(
                    model=self.model,
                    max_tokens=1024,
                    system=SYSTEM_PROMPT,
                    messages=messages,
                    tools=ANTHROPIC_TOOLS,
                )

                if response.stop_reason != "tool_use":
                    # Final answer received
                    final_text = ""
                    for block in response.content:
                        if hasattr(block, "text"):
                            final_text += block.text

                    return {
                        "status": "ok",
                        "backend": "llm",
                        "model": self.model,
                        "answer": final_text,
                        "evidence": evidence_collected,
                        "warnings": warnings_collected,
                    }

                # Process tool calls
                messages.append({"role": "assistant", "content": response.content})
                tool_results = []
                for block in response.content:
                    if block.type == "tool_use":
                        t_name = block.name
                        t_input = block.input
                        t_res = self.execute_tool(t_name, t_input)
                        sanitized_res = sanitize_tool_output(t_res)

                        if "evidence" in t_res:
                            evidence_collected.append(t_res["evidence"])
                        if "warnings" in t_res:
                            warnings_collected.extend(t_res["warnings"])

                        tool_results.append({
                            "type": "tool_result",
                            "tool_use_id": block.id,
                            "content": json.dumps(sanitized_res),
                        })

                messages.append({"role": "user", "content": tool_results})

            # If loop finished without stop_reason != 'tool_use', fallback
            return self.offline_assistant.answer(question, district_context=district_context)

        except Exception as err:
            # Graceful fallback to offline backend on network error, key error, or timeout
            offline_res = self.offline_assistant.answer(question, district_context=district_context)
            offline_res["fallback_from_llm"] = True
            offline_res["fallback_reason"] = str(err)
            offline_res["warnings"].append(f"LLM backend unavailable ({err}); answered via offline deterministic backend.")
            return offline_res
